import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const contractPath = process.env.OWLVIGIL_OPENAPI_SPEC
  ? resolve(process.env.OWLVIGIL_OPENAPI_SPEC)
  : resolve(root, "contracts/management-contract.json");
const contract = JSON.parse(readFileSync(contractPath, "utf8"));

function methodName(operationId) {
  return operationId
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part, index) => index === 0 ? part.toLowerCase() : part[0].toUpperCase() + part.slice(1))
    .join("");
}

const operations = Object.keys(contract.operations).sort();
const names = new Map();
const preferredNames = new Set(["getBillingOverview"]);
const methods = [];
for (const operationId of operations) {
  const baseName = methodName(operationId);
  const name = preferredNames.has(baseName) ? `${baseName}Operation` : baseName;
  if (names.has(name)) throw new Error(`management method name collision: ${name}`);
  names.set(name, operationId);
  methods.push(`  ${name}(request: ManagementOperationRequest & { body?: ManagementOperationBody["${operationId}"] } = {}): Promise<ApiResponse<ManagementOperationData["${operationId}"]>> {`);
  methods.push(`    return this.openApi("${operationId}", request);`);
  methods.push("  }");
}

const output = `// Code generated by scripts/generate-management-methods.mjs; DO NOT EDIT.\n\nimport type { ApiResponse, ManagementOperationRequest } from "./index.js";\nimport type { ManagementOperationBody, ManagementOperationData } from "./management-types.js";\nimport type { ManagementOperationId } from "./management-operations.js";\n\nexport abstract class GeneratedManagementMethods {\n  abstract openApi<K extends ManagementOperationId>(operationId: K, request?: ManagementOperationRequest & { body?: ManagementOperationBody[K] }): Promise<ApiResponse<ManagementOperationData[K]>>;\n\n${methods.join("\n")}\n}\n`;

writeFileSync(resolve(root, "src/management-methods.ts"), output);
console.log(`generated ${operations.length} Management convenience methods`);
